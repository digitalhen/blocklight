import { readFile, writeFile } from 'node:fs/promises';
import { marked } from 'marked';
const root = new URL('../../', import.meta.url);
let guide = await readFile(new URL('docs/guide.md', root), 'utf8');
for (const name of ['basic', 'datasets']) {
  const code = await readFile(new URL(`playground/examples/${name}/main.ts`, root), 'utf8');
  guide = guide.replace(`{{example:${name}}}`, '```ts\n' + code + '```');
}
const outputs = new Map([
  ['packages/blocklight/CHANGELOG.md', await readFile(new URL('CHANGELOG.md', root), 'utf8')],
  ['README.md', '<!-- Generated by npm run docs:build. Edit docs/guide.md. -->\n' + guide],
  ['packages/blocklight/README.md', '<!-- Generated by npm run docs:build. Edit docs/guide.md. -->\n' + guide],
  ['playground/docs.html', `<!doctype html><html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Blocklight documentation</title><link rel="stylesheet" href="/src/style.css"></head><body><header><a class="brand" href="./">blocklight</a><nav><a href="./">Playground</a><a href="./examples/basic/">Basic example</a><a href="./examples/datasets/">Datasets</a><a href="./examples/chicago/">Chicago</a></nav></header><main class="docs">${marked.parse(guide)}</main></body></html>`],
]);
let index = await readFile(new URL('playground/index.html', root), 'utf8');
const escape = value => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
for (const [id, name] of [['basic-code', 'basic'], ['complex-code', 'datasets']]) {
  const source = await readFile(new URL(`playground/examples/${name}/main.ts`, root), 'utf8');
  index = index.replace(new RegExp(`(<code id="${id}">)[\\s\\S]*?(</code>)`), (_match, before, after) => before + escape(source) + after);
}
outputs.set('playground/index.html', index);
for (const [path, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(new URL(path, root), 'utf8').catch(() => '') !== content) throw new Error(`${path} is stale. Run npm run docs:build.`);
  } else await writeFile(new URL(path, root), content);
}
console.log(process.argv.includes('--check') ? 'Documentation is in sync.' : 'Generated site and both READMEs from the guide and runnable examples.');
